import subprocess
import sys
from pathlib import Path


CHECK = Path(__file__).resolve().parents[3] / "scripts" / "check_comments.py"


def commit(repo: Path) -> None:
    subprocess.run(["git", "add", "."], cwd=repo, check=True, capture_output=True)
    subprocess.run(
        ["git", "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid",
         "-c", "commit.gpgsign=false", "commit", "-m", "fixture"],
        cwd=repo, check=True, capture_output=True,
    )


def lint(repo: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(CHECK), "--base", "HEAD"],
        cwd=repo, capture_output=True, text=True, encoding="utf-8", check=False,
    )


def test_comment_lint_rejects_existing_suppressions_and_new_prose(tmp_path: Path) -> None:
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    (tmp_path / "checks.py").write_text(
        "# SPDX-License-Identifier: GPL-3.0-or-later\n"
        "value = 1  # ty: ignore[invalid-assignment]\n"
        "text = '# type: ignore'\n"
        "# Legacy constraint\n",
        encoding="utf-8",
    )
    (tmp_path / "checks.ts").write_text(
        "/* Legacy constraint *//* @ts-nocheck */\nconst value = 1;\n", encoding="utf-8",
    )
    workflow = tmp_path / ".github/workflows/verify.yml"
    workflow.parent.mkdir(parents=True)
    workflow.write_text(
        "jobs:\n  check:\n    runs-on: ubuntu-latest\n    steps:\n"
        "      - shell: python\n        run: |\n          value = 1  # noqa\n"
        "      - uses: actions/github-script@v8\n        with:\n          script: |\n"
        "            // eslint-disable-next-line no-undef\n            fail();\n",
        encoding="utf-8",
    )
    commit(tmp_path)
    (tmp_path / "new.jsx").write_text("const value = 1; // Explain the value\n", encoding="utf-8")
    result = lint(tmp_path)
    assert result.returncode == 1, result.stdout + result.stderr
    assert {line.split(": ", 1)[0] for line in result.stdout.splitlines() if ": " in line} == {
        ".github/workflows/verify.yml:7",
        ".github/workflows/verify.yml:11",
        "checks.py:2",
        "checks.ts:1",
        "new.jsx:1",
    }


def test_comment_lint_keeps_metadata_and_counts_occurrences_by_path(tmp_path: Path) -> None:
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    existing = tmp_path / "existing.py"
    existing.write_text("# Legacy constraint\n", encoding="utf-8")
    commit(tmp_path)
    package = tmp_path / "r/RCMetaR"
    (package / "man").mkdir(parents=True)
    (package / "R").mkdir()
    (package / "R" / "report.R").write_text("#' Summarize results\n", encoding="utf-8")
    (package / "man" / "report.Rd").write_text(
        "% Generated by roxygen2: do not edit by hand\n"
        "% Please edit documentation in R/report.R\n"
        "\\name{report}\n",
        encoding="utf-8",
    )
    (tmp_path / "tool.py").write_text(
        "#!/usr/bin/env python3\n# SPDX-License-Identifier: GPL-3.0-or-later\n"
        "label = '# noqa'\n", encoding="utf-8",
    )
    workflow = tmp_path / ".github/workflows/verify.yml"
    workflow.parent.mkdir(parents=True)
    workflow.write_text(
        "jobs:\n  check:\n    runs-on: ubuntu-latest\n    steps:\n"
        f"      - uses: actions/checkout@{'a' * 40} # v6\n",
        encoding="utf-8",
    )
    (tmp_path / "formatted.js").write_text(
        "// prettier-ignore\nconst   value = 1;\n", encoding="utf-8",
    )
    existing.write_text("\n# Legacy constraint\n", encoding="utf-8")
    result = lint(tmp_path)
    assert result.returncode == 0, result.stdout + result.stderr

    existing.write_text("# Legacy constraint\n# Legacy constraint\n", encoding="utf-8")
    (tmp_path / "moved.py").write_text("# Legacy constraint\n", encoding="utf-8")
    result = lint(tmp_path)
    assert result.returncode == 1, result.stdout + result.stderr
    assert "existing.py:2: new comment" in result.stdout
    assert "moved.py:1: new comment" in result.stdout
